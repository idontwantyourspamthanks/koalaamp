/// Webamp `UC`: combining marks are dropped after folding.
constexpr bool isCombiningMark(char32_t cp) {
    return (cp >= 0x0300 && cp <= 0x036F) || (cp >= 0xFE20 && cp <= 0xFE2F) ||
           (cp >= 0x20D0 && cp <= 0x20FF);
}

